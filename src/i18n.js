const RTL = ['ar', 'ur']; // right-to-left languages
let lang = 'en';

export const LANGS = Object.entries(STRINGS).map(([code, s]) => ({ code, name: s.name }));
export const getLang = () => lang;

export function setLang(code) {
  lang = STRINGS[code] ? code : 'en';
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL.includes(lang) ? 'rtl' : 'ltr';
}

// t('meals', { n: 5 }) → "5 meals shared" (in the chosen language; English if a word is missing)
export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
